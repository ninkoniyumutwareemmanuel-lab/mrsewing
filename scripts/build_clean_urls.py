#!/usr/bin/env python3
"""Build GitHub Pages directory indexes from existing standalone HTML sources.

Preferred URLs end in /. Originals remain useful, canonicalized fallback pages
and perform a query/hash-preserving client redirect when JavaScript is enabled.
There are no claimed server-side redirects for legacy .html URLs.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DOMAIN = 'https://mrsewingfashion.com'
# ARD permits any linked entry source. Root JSON works on both static hosts
# without changing hidden-directory/Jekyll rules or robots.txt SEO directives.
DISCOVERY_LINKS = ('<link rel="ard" type="application/json" href="/ai-catalog.json">\n  '
                   '<link rel="ai-catalog" type="application/json" href="/ai-catalog.json">')
LEGACY = re.compile(r'\s*<script data-legacy-url>.*?</script>', re.S)


def routes():
    aliases=json.loads((ROOT/'_data/route-aliases.json').read_text())
    return {name: aliases.get(name,'/' if name == 'index.html' else '/' + name.removesuffix('.html') + '/')
            for name in json.loads((ROOT / '_data/page-seo.json').read_text())}


def legacy_script(name):
    target = routes()[name]
    return ('<script data-legacy-url>if (location.pathname === ' + json.dumps('/' + name)
            + ') location.replace(' + json.dumps(target) + ' + location.search + location.hash);</script>')


def clean_document(name):
    source = (ROOT / name).read_text()
    source = LEGACY.sub('', source)
    source = re.sub(r'<base\b[^>]*>', '', source, flags=re.I)
    aliases=json.loads((ROOT/'_data/route-aliases.json').read_text())
    if name in aliases:source=source.replace('<head>', '<head><script data-alias-route>location.replace('+json.dumps(aliases[name])+'+location.search+location.hash)</script>',1)
    # Root base keeps inline CSS backgrounds, srcset, video, scripts and dynamic
    # component fetches at their existing origin-root locations. All fragment
    # links are explicitly page-qualified during URL migration.
    source, count = re.subn(r'<head\b[^>]*>', lambda m: m[0] + '\n  <base href="/">\n  ' + DISCOVERY_LINKS, source, count=1, flags=re.I)
    if count != 1:
        raise ValueError(f'Expected one head: {name}')
    source = '\n'.join(line.rstrip() for line in source.splitlines()) + '\n'
    return '<!-- Generated by scripts/build_clean_urls.py; edit the root HTML source. -->\n' + source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, route in routes().items():
        if route == '/':
            continue
        path = ROOT / name.removesuffix('.html') / 'index.html'
        output = clean_document(name)
        if not path.exists() or path.read_text() != output:
            stale.append(route)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(output)
    if args.check and stale:
        raise SystemExit('Clean pages are out of date: ' + ', '.join(stale))
    print('PASS: all 31 clean directory pages match their source.' if args.check else f'Generated {len(stale)} clean directory pages; source HTML and originals preserved.')


if __name__ == '__main__':
    main()
