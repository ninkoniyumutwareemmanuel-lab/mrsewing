"""Render H01 metadata from its existing, effective public SEO/business records.

``public-page-seo.json['/']`` owns the homepage title and description. The
legacy ``page-seo.json['index.html']`` entry is retained for route compatibility,
but is not an editable homepage metadata source. ``business.json`` is the
existing shared business/schema projection; its hours are generated by
sync_business_hours.py. No customer data or advertising configuration belongs
in this renderer.
"""
from copy import deepcopy
from html import escape
import json
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]


def _text(record, key):
    value = record.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"Homepage metadata requires nonempty {key}")
    return value


def _https_url(value, field):
    parsed = urlsplit(value)
    if parsed.scheme != 'https' or not parsed.netloc or parsed.username or parsed.password:
        raise ValueError(f"Homepage metadata requires an absolute HTTPS {field}")
    return value


def render_head(root=ROOT, *, seo=None, business=None, media=None):
    """Return metadata only; styles, scripts and preload hooks stay in template.

    Optional records support isolated fixtures without mutating approved data.
    Escaping protects both HTML attributes and the JSON-LD script boundary.
    Environment-specific robots overrides remain owned by site_seo.finalize
    and the private preview server, rather than a second indexing switch here.
    """
    root = Path(root)
    if seo is None:
        seo = json.loads((root / '_data/public-page-seo.json').read_text())['/']
    if business is None:
        business = json.loads((root / '_data/business.json').read_text())
    if media is None:
        media = json.loads((root / '_data/homepage-media.json').read_text())
    seo, business = deepcopy(seo), deepcopy(business)
    title, description = _text(seo, 'title'), _text(seo, 'description')
    name = _text(business, 'name')
    canonical = _https_url(_text(business, 'url'), 'business URL')
    image = _https_url(_text(business, 'image'), 'social image URL')
    logo_alt = f'{name} official MS brand logo'
    website = {
        '@type': 'WebSite', '@id': canonical + '#website', 'url': canonical,
        'name': name, 'alternateName': [name, 'Mr Sewing', 'mr_sewing_fashion', 'mrsewingfashion'],
        'publisher': business,
    }
    structured = {'@context': 'https://schema.org', '@graph': [website]}
    encoded = json.dumps(structured, ensure_ascii=False, indent=2).replace('<', '\\u003c').replace('>', '\\u003e').replace('&', '\\u0026')
    def meta(key, value, property=False):
        attribute = 'property' if property else 'name'
        return f'<meta {attribute}="{escape(key, quote=True)}" content="{escape(str(value), quote=True)}">'
    lines = [
        '<title>' + escape(title, quote=False) + '</title>',
        meta('description', description), meta('author', name),
        meta('robots', 'index, follow'),
        '<link rel="canonical" href="' + escape(canonical, quote=True) + '">',
        '<link rel="icon" href="/assets/images/logo-icon.png" type="image/png">',
        '<link rel="shortcut icon" href="/assets/images/logo-icon.png" type="image/png">',
        '<link rel="apple-touch-icon" href="/assets/images/logo-icon.png">',
    ]
    for key, value in [
        ('og:site_name', name), ('og:title', title), ('og:description', description),
        ('og:type', 'website'), ('og:url', canonical), ('og:image', image),
        ('og:image:secure_url', image), ('og:image:alt', logo_alt), ('og:locale', 'en_US'),
    ]:
        lines.append(meta(key, value, property=True))
    image_path = unquote(urlsplit(image).path).lstrip('/')
    if image_path in media:
        dimensions = media[image_path]
        if not all(isinstance(dimensions.get(key), int) and dimensions[key] > 0 for key in ('width', 'height')):
            raise ValueError('Homepage social image dimensions must be positive integers')
        for key in ('width', 'height'):
            lines.append(meta('og:image:' + key, dimensions[key], property=True))
    image_type = {'.jpeg': 'image/jpeg', '.jpg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp', '.avif': 'image/avif'}.get(Path(image_path).suffix.lower())
    if image_type:
        lines.append(meta('og:image:type', image_type, property=True))
    for key, value in [
        ('twitter:card', 'summary_large_image'), ('twitter:title', title),
        ('twitter:description', description), ('twitter:image', image), ('twitter:image:alt', logo_alt),
    ]:
        lines.append(meta(key, value))
    lines.append('<script type="application/ld+json">\n' + encoded + '\n</script>')
    return '\n  '.join(lines)
