#!/usr/bin/env python3
"""Generate the server's current approved fee inputs; never a public price list.

The source remains customer-policy-facts.json. This module is a build artifact,
not a separately editable schedule. No customer data or confidential costs exist
here. Public service presentation uses public_content.py instead.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    source = json.loads((ROOT / '_data/customer-policy-facts.json').read_text())
    result = {
        'consultationAndFittingRwf': source['mobile']['consultationAndFittingRwf'],
        'confirmedOrderMeasurementVisitRwf': source['mobile']['confirmedOrderMeasurementVisitRwf'],
        'outsideKigaliRwandaPerGarmentRwf': source['customTailoringDelivery']['outsideKigaliRwandaPerGarmentRwf'],
    }
    assert all(type(v) is int and v > 0 for v in result.values())
    text = ('/* Generated by scripts/build_operational_facts.py from approved customer-policy-facts.json. */\n'
            'export const operationalFacts = Object.freeze(' + json.dumps(result, sort_keys=True) + ');\n')
    return {ROOT / 'functions/_lib/operational-facts.js': text}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit('Stale approved operational facts: ' + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print('PASS generated server fee inputs match the single approved source')


if __name__ == '__main__':
    main()
